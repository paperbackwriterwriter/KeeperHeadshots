// Captures the rendered HTML of each public page (lib/seo.js PAGES) from a
// running local server and writes lib/prerendered.js, which the server embeds
// in its HTML so crawlers that don't run JavaScript still see the content.
//
//   npm start &            # or any server on BASE
//   npm run prerender      # then commit lib/prerendered.js
//
// Re-run after changing the copy on any public page.
import fs from "node:fs";
import { chromium } from "playwright";
import { PAGES } from "../lib/seo.js";

const BASE = process.env.BASE || "http://localhost:3100";
const OUT = new URL("../lib/prerendered.js", import.meta.url);

// CHROMIUM_PATH (or a preinstalled /opt/pw-browsers/chromium) if present,
// otherwise Playwright's own browser.
const exe = [process.env.CHROMIUM_PATH, "/opt/pw-browsers/chromium"].find((p) => p && fs.existsSync(p));
const browser = await chromium.launch(exe ? { executablePath: exe } : {});
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
// Only the page's own markup matters; skip third-party requests.
await page.route(/^https?:\/\/(?!localhost|127\.0\.0\.1)/, (r) => r.abort());

const clean = (html) =>
  html
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\sdata-reveal(="[^"]*")?/g, "")
    .replace(/\saria-busy="[^"]*"/g, "")
    .replace(/\bview-enter\b/g, "")
    .replace(/\s+class="\s*"/g, "")
    .replace(/>\s+</g, "> <")
    .trim();

const out = {};
for (const path of Object.keys(PAGES)) {
  await page.goto(BASE + path, { waitUntil: "networkidle" });
  await page.waitForSelector("#app main h1");
  await page.waitForTimeout(300);
  const html = await page.evaluate(() => {
    const app = document.getElementById("app").cloneNode(true);
    app.querySelectorAll(".toast, [data-prerender-skip]").forEach((el) => el.remove());
    return app.innerHTML;
  });
  out[path] = clean(html);
  console.log(`${path.padEnd(10)} ${String(out[path].length).padStart(6)} chars`);
}
await browser.close();

fs.writeFileSync(OUT, `// Generated by \`npm run prerender\`. Do not edit by hand.\nexport const PRERENDERED = ${JSON.stringify(out, null, 2)};\n`);
console.log("wrote lib/prerendered.js");
