// Bundles the Lucide icons the UI uses into public/js/icons.js (a static file,
// so it's served straight from the CDN on Vercel). Re-run after adding an icon.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ICONS = [
  "arrow-right", "arrow-left", "arrow-up-right", "camera", "check", "check-circle-2", "circle-alert", "x", "upload", "image-plus",
  "sparkles", "shield-check", "clock-3", "download", "star", "trash-2", "log-out", "plus", "refresh-cw", "sun", "focus", "scan-face",
  "smile", "badge-check", "users", "building-2", "lock", "zap", "chevron-down", "menu", "loader", "eye", "eye-off", "wand-sparkles",
  "crown", "aperture", "info", "briefcase", "rotate-ccw", "mail", "pencil", "play", "layers", "user-round",
  "send", "receipt", "circle-help", "mail-check", "pause", "house", "id-card", "signpost", "share-2", "globe", "file-user", "video", "contact-round", "search-check", "stethoscope", "map-pin", "calendar-check", "mic", "scale", "newspaper",
];
const dir = path.join(root, "node_modules/lucide-static/icons");
const map = {};
for (const n of ICONS) {
  const f = path.join(dir, `${n}.svg`);
  if (!fs.existsSync(f)) {
    console.warn(`missing icon: ${n}`);
    continue;
  }
  const svg = fs.readFileSync(f, "utf8");
  map[n] = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s+/g, " ").trim();
}
fs.writeFileSync(path.join(root, "public/js/icons.js"), `// Generated by scripts/build-icons.js — Lucide icons (ISC license).\nexport const ICONS = ${JSON.stringify(map)};\n`);
console.log(`icons.js: ${Object.keys(map).length} icons`);
